/**
 * English catalog of the desktop app. It is the source of truth: the keys of
 * this object are the MessageKey type, so a catalog of another language cannot
 * miss one.
 *
 * The keys are grouped by area. A plural message has one form for English and
 * the forms of the other languages it serves; "other" is required.
 */

/** Forms of a plural message, by CLDR plural category. */

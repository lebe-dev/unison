// watchBuffer is the number of snapshots buffered before the watcher blocks.
const watchBuffer = 16

// maxFiles bounds the file paths of one pasteboard change.
const maxFiles = 16

// Watch delivers a snapshot for every pasteboard change until ctx is done. The
// current content at the start of watching is not reported.
func (c *Clipboard) Watch(ctx context.Context) (<-chan ports.Snapshot, error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	baseline := C.uc_poll(0, nil, C.size_t(maxFiles))
	snapshots := make(chan ports.Snapshot, watchBuffer)
	go c.watch(ctx, baseline, snapshots)
	return snapshots, nil
}

// watch polls the change counter and forwards snapshots of every change.
func (c *Clipboard) watch(ctx context.Context, baseline C.NSInteger, out chan<- ports.Snapshot) {
	defer close(out)
	previous := baseline
	ticker := time.NewTicker(c.interval)
	defer ticker.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-ticker.C:
		}
		var raw C.uc_snapshot
		//nolint:gocritic // false positive from the cgo-generated pointer check
		count := C.uc_poll(previous, &raw, C.size_t(maxFiles))
		if count == previous {
			continue
		}
		previous = count
		snapshot, ok := snapshotFrom(&raw)
		if !ok {
			continue
		}
		select {
		case out <- snapshot:
		case <-ctx.Done():
			return
		}
	}
}

// snapshotFrom converts a pasteboard read into a snapshot and releases the C
// buffers. It reports false when the change carries nothing to capture.
func snapshotFrom(raw *C.uc_snapshot) (ports.Snapshot, bool) {
	defer C.uc_snapshot_free(raw)

	owned := raw.owned != 0
	if raw.sensitive != 0 {
		return ports.Snapshot{Sensitive: true, OwnedByUs: owned}, true
	}

	paths := cFilePaths(raw)
	reps := make([]ports.Representation, 0, 3+len(paths))
	if raw.plain != nil {
		reps = append(reps, ports.Representation{
			MIME: MIMETextPlain,
			Data: C.GoBytes(raw.plain, C.int(raw.plain_len)),
		})
	}
	if raw.html != nil {
		reps = append(reps, ports.Representation{
			MIME: MIMETextHTML,
			Data: C.GoBytes(raw.html, C.int(raw.html_len)),
		})
	}
	if raw.png != nil {
		reps = append(reps, ports.Representation{
			MIME: MIMEImagePNG,
			Data: C.GoBytes(raw.png, C.int(raw.png_len)),
		})
	}
	for _, path := range paths {
		reps = append(reps, ports.Representation{MIME: MIMEUnisonFile, FilePath: path})
	}
	if len(reps) == 0 {
		return ports.Snapshot{}, false
	}
	return ports.Snapshot{
		Content:   ports.Content{Representations: reps},
		OwnedByUs: owned,
	}, true
}

// cFilePaths copies the file paths of a pasteboard read into Go strings.
func cFilePaths(raw *C.uc_snapshot) []string {
	if raw.paths == nil || raw.files == 0 {
		return nil
	}
	pointers := unsafe.Slice(raw.paths, int(raw.files))
	paths := make([]string, 0, len(pointers))
	for _, path := range pointers {
		if path != nil {
			paths = append(paths, C.GoString(path))
		}
	}
	return paths
}

// Write replaces the pasteboard content with the given representations and
// marks it as written by this application. Text and a PNG image share one
// pasteboard item, every file becomes an item with a file URL. Files win when
// content carries them together with text or an image.
func (c *Clipboard) Write(ctx context.Context, content ports.Content) error {
	if err := ctx.Err(); err != nil {
		return err
	}

	var (
		plain, html, png          []byte
		hasPlain, hasHTML, hasPNG bool
		files                     []string
	)
	for _, rep := range content.Representations {
		switch {
		case rep.MIME == MIMETextPlain && len(rep.Data) > 0:
			plain, hasPlain = rep.Data, true
		case rep.MIME == MIMETextHTML && len(rep.Data) > 0:
			html, hasHTML = rep.Data, true
		case rep.MIME == MIMEImagePNG && len(rep.Data) > 0:
			png, hasPNG = rep.Data, true
		case rep.FilePath != "":
			files = append(files, rep.FilePath)
		default:
			return fmt.Errorf("%w: mime %q", ErrUnsupportedContent, rep.MIME)
		}
	}

	if len(files) > 0 {
		return writeFiles(files)
	}
	if !hasPlain && !hasHTML && !hasPNG {
		return ErrUnsupportedContent
	}

	plainPtr := cBytes(plain)
	defer C.free(plainPtr)
	htmlPtr := cBytes(html)
	defer C.free(htmlPtr)
	pngPtr := cBytes(png)
	defer C.free(pngPtr)

	if C.uc_write(plainPtr, C.size_t(len(plain)), cBool(hasPlain),
		htmlPtr, C.size_t(len(html)), cBool(hasHTML),
		pngPtr, C.size_t(len(png)), cBool(hasPNG)) != 0 {
		return errors.New("clipboard: write pasteboard failed")
	}
	return nil
}

// writeFiles puts one file URL item per path on the pasteboard.
func writeFiles(files []string) error {
	if len(files) > maxFiles {
		return fmt.Errorf("%w: %d files", ErrUnsupportedContent, len(files))
	}
	paths := make([]*C.char, 0, len(files))
	for _, file := range files {
		if !filepath.IsAbs(file) {
			return fmt.Errorf("%w: path %q is not absolute", ErrUnsupportedContent, file)
		}
		path := C.CString(file)
		defer C.free(unsafe.Pointer(path))
		paths = append(paths, path)
	}
	if C.uc_write_files(&paths[0], C.size_t(len(paths))) != 0 {
		return errors.New("clipboard: write pasteboard failed")
	}
	return nil
}

// AccessBehavior reports how the system treats programmatic pasteboard reads.
// Systems without the pasteboard permission model report BehaviorAlwaysAllow.
func (c *Clipboard) AccessBehavior(ctx context.Context) (Behavior, error) {
	if err := ctx.Err(); err != nil {
		return BehaviorDefault, err
	}
	return Behavior(C.uc_access_behavior()), nil
}

// cBytes copies data into a malloc buffer. An empty payload has no buffer.
func cBytes(data []byte) unsafe.Pointer {
	if len(data) == 0 {
		return nil
	}
	return C.CBytes(data)
}

func cBool(value bool) C.int {
	if value {
		return 1
	}
	return 0
}

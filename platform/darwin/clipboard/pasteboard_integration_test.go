//go:build darwin && cgo && pasteboardtest

package clipboard

import (
	"context"
	"errors"
	"os"
	"testing"
	"time"

	"github.com/lebe-dev/unison/core/ports"
)

const (
	testInterval = 100 * time.Millisecond
	testTimeout  = 3 * time.Second
)

// TestMain preserves the user clipboard around the tests, which change it.
func TestMain(m *testing.M) {
	saved := savePasteboard()
	code := m.Run()
	restorePasteboard(saved)
	os.Exit(code)
}

func newClipboard(t *testing.T) *Clipboard {
	t.Helper()
	c, err := New(Options{PollInterval: testInterval})
	if err != nil {
		t.Fatalf("New: %v", err)
	}
	return c
}

func watch(t *testing.T) (<-chan ports.Snapshot, func()) {
	t.Helper()
	ctx, cancel := context.WithCancel(context.Background())
	snapshots, err := newClipboard(t).Watch(ctx)
	if err != nil {
		cancel()
		t.Fatalf("Watch: %v", err)
	}
	t.Cleanup(cancel)
	return snapshots, cancel
}

func next(t *testing.T, snapshots <-chan ports.Snapshot) ports.Snapshot {
	t.Helper()
	select {
	case snapshot, ok := <-snapshots:
		if !ok {
			t.Fatal("snapshot channel closed")
		}
		return snapshot
	case <-time.After(testTimeout):
		t.Fatal("no snapshot within the timeout")
	}
	return ports.Snapshot{}
}

func expectNone(t *testing.T, snapshots <-chan ports.Snapshot, wait time.Duration) {
	t.Helper()
	select {
	case snapshot, ok := <-snapshots:
		if ok {
			t.Fatalf("unexpected snapshot with %d representations", len(snapshot.Content.Representations))
		}
	case <-time.After(wait):
	}
}

func TestWriteTextAndHTML(t *testing.T) {
	snapshots, _ := watch(t)
	c := newClipboard(t)

	content := ports.Content{Representations: []ports.Representation{
		{MIME: MIMETextPlain, Data: []byte("hello")},
		{MIME: MIMETextHTML, Data: []byte("<b>hello</b>")},
	}}
	if err := c.Write(context.Background(), content); err != nil {
		t.Fatalf("Write: %v", err)
	}

	snapshot := next(t, snapshots)
	if !snapshot.OwnedByUs {
		t.Fatal("OwnedByUs = false, want true")
	}
	if snapshot.Sensitive {
		t.Fatal("Sensitive = true, want false")
	}
	reps := snapshot.Content.Representations
	if len(reps) != 2 {
		t.Fatalf("got %d representations, want 2", len(reps))
	}
	if reps[0].MIME != MIMETextPlain || string(reps[0].Data) != "hello" {
		t.Fatalf("first representation is %s %q", reps[0].MIME, reps[0].Data)
	}
	if reps[1].MIME != MIMETextHTML || string(reps[1].Data) != "<b>hello</b>" {
		t.Fatalf("second representation is %s %q", reps[1].MIME, reps[1].Data)
	}
}

func TestWriteHTMLOnly(t *testing.T) {
	snapshots, _ := watch(t)
	c := newClipboard(t)

	content := ports.Content{Representations: []ports.Representation{
		{MIME: MIMETextHTML, Data: []byte("<i>only</i>")},
	}}
	if err := c.Write(context.Background(), content); err != nil {
		t.Fatalf("Write: %v", err)
	}

	snapshot := next(t, snapshots)
	reps := snapshot.Content.Representations
	if len(reps) != 1 || reps[0].MIME != MIMETextHTML {
		t.Fatalf("got %d representations, want one HTML", len(reps))
	}
}

func TestWriteRejectsUnsupportedMIME(t *testing.T) {
	c := newClipboard(t)
	content := ports.Content{Representations: []ports.Representation{
		{MIME: "image/png", Data: []byte{0x89, 'P', 'N', 'G'}},
	}}
	if err := c.Write(context.Background(), content); !errors.Is(err, ErrUnsupportedContent) {
		t.Fatalf("Write error = %v, want ErrUnsupportedContent", err)
	}
}

func TestSensitiveMarkers(t *testing.T) {
	for _, marker := range []string{
		"org.nspasteboard.ConcealedType",
		"org.nspasteboard.TransientType",
		"org.nspasteboard.AutoGeneratedType",
	} {
		t.Run(marker, func(t *testing.T) {
			snapshots, _ := watch(t)
			writeMarkedText("secret", marker)

			snapshot := next(t, snapshots)
			if !snapshot.Sensitive {
				t.Fatal("Sensitive = false, want true")
			}
			if len(snapshot.Content.Representations) != 0 {
				t.Fatalf("got %d representations for sensitive content, want none", len(snapshot.Content.Representations))
			}
		})
	}
}

func TestCurrentContentIsNotReported(t *testing.T) {
	writePlainText("before the watch")
	snapshots, _ := watch(t)
	expectNone(t, snapshots, 3*testInterval)

	writePlainText("after the watch")
	snapshot := next(t, snapshots)
	if got := string(snapshot.Content.Representations[0].Data); got != "after the watch" {
		t.Fatalf("snapshot content = %q, want %q", got, "after the watch")
	}
}

func TestWatchStopsWithContext(t *testing.T) {
	snapshots, cancel := watch(t)
	cancel()

	select {
	case _, ok := <-snapshots:
		if ok {
			t.Fatal("received a snapshot after cancel")
		}
	case <-time.After(testTimeout):
		t.Fatal("snapshot channel was not closed")
	}
}

func TestWriteClearsPreviousContent(t *testing.T) {
	snapshots, _ := watch(t)
	writePlainText("previous")
	next(t, snapshots)

	c := newClipboard(t)
	content := ports.Content{Representations: []ports.Representation{
		{MIME: MIMETextPlain, Data: []byte("current")},
	}}
	if err := c.Write(context.Background(), content); err != nil {
		t.Fatalf("Write: %v", err)
	}

	snapshot := next(t, snapshots)
	reps := snapshot.Content.Representations
	if len(reps) != 1 || string(reps[0].Data) != "current" {
		t.Fatalf("got %d representations, want only %q", len(reps), "current")
	}
}

func TestAccessBehavior(t *testing.T) {
	c := newClipboard(t)
	behavior, err := c.AccessBehavior(context.Background())
	if err != nil {
		t.Fatalf("AccessBehavior: %v", err)
	}
	switch behavior {
	case BehaviorDefault, BehaviorAsk, BehaviorAlwaysAllow, BehaviorAlwaysDeny:
	default:
		t.Fatalf("AccessBehavior = %d, want a known behavior", behavior)
	}
}
